# -*- coding: utf-8 -*-
"""
complex_euler.py
================

Реализация двух методов численного решения ОДУ:

1. classic_euler         — обычный (вещественный) явный метод Эйлера, 1-й порядок.
2. complex_two_step_euler — 2-шаговый метод Эйлера с КОМПЛЕКСНЫМИ шагами,
                            который повторяет эксперимент из раздела 2
                            статьи George, Jung, Mangan (arXiv:2110.04402).
                            Имеет 2-й порядок точности для вещественных ОДУ.

Идея «комплексного» метода: вместо того, чтобы делать два вещественных шага
длины Δt/2, делается один комплексный шаг w1·Δt = (Δt/2 + i·Δt/2) и
сопряжённый ему второй комплексный шаг w2·Δt = (Δt/2 − i·Δt/2). Сумма шагов
снова даёт вещественный Δt (мы возвращаемся на действительную ось). При этом
для вещественной задачи у численного решения автоматически появляется
дополнительный член разложения, совпадающий с членом ряда Тейлора 2-го
порядка — то есть метод становится 2-го порядка точности по Δt при том же
количестве вычислений правой части f(t, y).

После завершения пары комплексных шагов мы берём вещественную часть Re(·),
так как мнимая составляющая представляет погрешность высших порядков, а сама
истинная физическая величина — вещественная.

Все функции принимают:
    f(t, y) → правая часть ОДУ ẏ = f(t, y) (может быть скалярной или векторной).
    y0       → начальное условие (число или np.ndarray).
    t0, tN   → начальный и конечный моменты времени.
    n_steps  → число «макрошагов» Δt = (tN − t0) / n_steps.

Возвращают: массив t размера (n_steps+1) и массив y значений решения тех же
размеров (для систем — двумерный массив).
"""

from __future__ import annotations

import numpy as np


# -----------------------------------------------------------------------------
# 1. КЛАССИЧЕСКИЙ ЯВНЫЙ МЕТОД ЭЙЛЕРА
# -----------------------------------------------------------------------------
def classic_euler(f, y0, t0: float, tN: float, n_steps: int):
    """Обычный явный метод Эйлера.

    Итерационная формула:  y_{k+1} = y_k + Δt · f(t_k, y_k)

    Глобальный порядок точности — 1-й, локальный — 2-й.

    Параметры
    ---------
    f : callable
        Правая часть ОДУ. Сигнатура f(t, y) → dy/dt.
    y0 : float | np.ndarray
        Начальное условие.
    t0, tN : float
        Границы интервала интегрирования.
    n_steps : int
        Число шагов сетки.

    Возвращает
    ----------
    t : np.ndarray, форма (n_steps + 1,)
        Массив временных точек.
    y : np.ndarray
        Численное решение на этих точках.
    """
    dt = (tN - t0) / n_steps
    t = np.linspace(t0, tN, n_steps + 1)

    # Подготовка массива решения. Поддерживаются скалярные и векторные ОДУ.
    y0_arr = np.atleast_1d(np.asarray(y0, dtype=float))
    y = np.empty((n_steps + 1, y0_arr.size), dtype=float)
    y[0] = y0_arr

    for k in range(n_steps):
        y[k + 1] = y[k] + dt * np.asarray(f(t[k], y[k]), dtype=float)

    # Если уравнение скалярное — возвращаем одномерный массив.
    if y.shape[1] == 1:
        return t, y[:, 0]
    return t, y


# -----------------------------------------------------------------------------
# 2. КОМПЛЕКСНЫЙ 2-ШАГОВЫЙ МЕТОД ЭЙЛЕРА (раздел 2 статьи)
# -----------------------------------------------------------------------------
# Два комплексных шага, в сумме дающие вещественный Δt и обеспечивающие
# 2-й порядок точности. Это «канонический» путь из работы George–Jung–Mangan.
W1 = 0.5 + 0.5j      # первый комплексный полу-шаг   (Δt/2 + i·Δt/2)
W2 = 0.5 - 0.5j      # второй комплексный полу-шаг   (Δt/2 − i·Δt/2)


def complex_two_step_euler(f, y0, t0: float, tN: float, n_steps: int,
                           weights: tuple[complex, complex] = (W1, W2)):
    """Двухшаговый Эйлер с КОМПЛЕКСНЫМИ шагами (Fig.1 статьи).

    Между двумя соседними узлами вещественной сетки делается ПАРА комплексных
    шагов длины w1·Δt и w2·Δt. После пары шагов берётся вещественная часть.

    Формулы:
        Шаг 1:  y* = y_k + w1·Δt · f(t_k, y_k)
        Шаг 2:  ỹ = y* + w2·Δt · f(t_k + w1·Δt, y*)
        Шаг 3:  y_{k+1} = Re(ỹ)

    Условие на коэффициенты (даёт 2-й порядок):
        w1 + w2 = 1,  w1·w2 = 1/2.

    Параметры идентичны classic_euler. Дополнительно можно передать собственные
    weights = (w1, w2), удовлетворяющие условиям выше (или специально нарушать
    их — для демонстрации потери порядка).
    """
    w1, w2 = weights
    # Проверка условий 1-го и 2-го порядка (мягко: выведем предупреждение,
    # если коэффициенты их сильно нарушают, — это полезно при экспериментах).
    eps = 1e-8
    if abs(w1 + w2 - 1) > eps:
        print(f"[complex_two_step_euler] ВНИМАНИЕ: w1+w2 = {w1+w2}, ожидалось 1.")
    if abs(w1 * w2 - 0.5) > eps:
        print(f"[complex_two_step_euler] ВНИМАНИЕ: w1·w2 = {w1*w2}, ожидалось 0.5.")

    dt = (tN - t0) / n_steps
    t = np.linspace(t0, tN, n_steps + 1)

    y0_arr = np.atleast_1d(np.asarray(y0, dtype=complex))
    y = np.empty((n_steps + 1, y0_arr.size), dtype=float)  # хранение — вещественное
    y[0] = y0_arr.real

    # «Рабочая» переменная — комплексная.
    yc = y0_arr.astype(complex)
    for k in range(n_steps):
        tk = t[k]
        # Промежуточная (комплексная!) точка после первого шага.
        y_star = yc + w1 * dt * np.asarray(f(tk, yc), dtype=complex)
        # Комплексное «время» в промежуточной точке.
        t_star = tk + w1 * dt
        # Финальная точка пары шагов.
        yc = y_star + w2 * dt * np.asarray(f(t_star, y_star), dtype=complex)
        # Возврат на действительную ось — берём только Re(·).
        yc = yc.real.astype(complex)
        y[k + 1] = yc.real

    if y.shape[1] == 1:
        return t, y[:, 0]
    return t, y


# -----------------------------------------------------------------------------
# 3. ВСПОМОГАТЕЛЬНЫЕ ФУНКЦИИ
# -----------------------------------------------------------------------------
def infinity_norm_error(y_num: np.ndarray, y_exact: np.ndarray) -> float:
    """Норма погрешности в сеточном чебышёвском (равномерном) виде ‖·‖_∞."""
    return float(np.max(np.abs(np.asarray(y_num) - np.asarray(y_exact))))


def stability_function_classic(z: np.ndarray) -> np.ndarray:
    """Φ(z) = 1 + z  — функция устойчивости классического Эйлера."""
    return 1.0 + z


def stability_function_complex2(z: np.ndarray) -> np.ndarray:
    """Φ(z) = 1 + z + z²/2  — функция устойчивости комплексного 2-шагового
    Эйлера (совпадает с функцией устойчивости 2-стадийного Рунге–Кутты)."""
    return 1.0 + z + 0.5 * z ** 2


def stability_function_complex3(z: np.ndarray) -> np.ndarray:
    """Φ(z) = 1 + z + z²/2 + z³/6 — для 3-шагового комплексного Эйлера
    (демонстрационно, не используется в основном эксперименте)."""
    return 1.0 + z + 0.5 * z ** 2 + (1.0 / 6.0) * z ** 3


