# -*- coding: utf-8 -*-
"""
equations.py
============

Каталог тестовых ОДУ из раздела 2 статьи George–Jung–Mangan (arXiv:2110.04402).

Каждая запись словаря EQUATIONS — это объект Equation:
    name      — короткое имя для подписей графиков (например, 'y' = y)
    f         — правая часть ОДУ; для системы 2-го порядка это уже сведённая
                к 1-му порядку система y = [u, v]ᵀ
    y0        — начальное условие (число или массив)
    t0, tN    — отрезок интегрирования
    exact     — точное решение (если известно), функция t → y;
                для систем возвращает массив [u, v] (или только u, см. комментарии)
    title     — подробное название
    description — комментарий: что именно демонстрирует пример

Используется в experiments.py, convergence.py и в GUI.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Callable, Optional

import numpy as np


# -----------------------------------------------------------------------------
# Базовый контейнер
# -----------------------------------------------------------------------------
@dataclass
class Equation:
    key: str                                  # ключ в словаре EQUATIONS
    name: str                                 # короткое имя для легенды
    title: str                                # длинное название
    f: Callable                                # правая часть ОДУ
    y0: object                                 # начальное условие
    t0: float
    tN: float
    exact: Optional[Callable] = None           # точное решение (если есть)
    description: str = ""                      # комментарий


# -----------------------------------------------------------------------------
# 1. ẏ = y, y(0) = 1  (Fig.1 статьи) — основная демонстрация роста точности
# -----------------------------------------------------------------------------
def _f_linear(t, y):
    return y                                   # ẏ = y


def _exact_linear(t):
    return np.exp(t)


# -----------------------------------------------------------------------------
# 2. ẏ = y², y(0) = 1  — нелинейное автономное ОДУ
# -----------------------------------------------------------------------------
def _f_square(t, y):
    return y * y                               # ẏ = y²


def _exact_square(t):
    # Аналитическое решение: y(t) = 1 / (1 − t), особенность в t = 1
    return 1.0 / (1.0 - t)


# -----------------------------------------------------------------------------
# 3. ẏ = 4 y sin³(t) cos(t), y(0) = 1  — нелинейное НЕавтономное
# -----------------------------------------------------------------------------
def _f_nlsin(t, y):
    s = np.sin(t)
    return 4.0 * y * s ** 3 * np.cos(t)


def _exact_nlsin(t):
    # Интегрируя dy/y = 4 sin³(t) cos(t) dt = d(sin⁴(t)),
    # получаем  y(t) = exp(sin⁴(t))
    return np.exp(np.sin(t) ** 4)


# -----------------------------------------------------------------------------
# 4. ẏ = cos(t), y(0) = 0  — линейное неавтономное
# -----------------------------------------------------------------------------
def _f_cos(t, y):
    return np.cos(t) * np.ones_like(y)


def _exact_cos(t):
    return np.sin(t)


# -----------------------------------------------------------------------------
# 5. ÿ = −y, y(0)=1, ẏ(0)=0  — гармонический осциллятор (система)
#    Состояние Y = [y, ẏ], тогда Ẏ = [Y[1], −Y[0]]
# -----------------------------------------------------------------------------
def _f_shm(t, Y):
    Y = np.atleast_1d(Y)
    return np.array([Y[1], -Y[0]])


def _exact_shm(t):
    # Возвращаем «составной» массив той же формы, что и Y у численного решения.
    # Удобнее сравнивать только первую компоненту (саму y).
    return np.stack([np.cos(t), -np.sin(t)], axis=-1)


# -----------------------------------------------------------------------------
# 6. ÿ = t·y, y(0)=1, ẏ(0)=0  (уравнение Эйри-типа, ÿ−t·y=0)
#    Хотя в стандартной форме уравнение Эйри имеет вид ÿ = t·y, его решения
#    выражаются через функции Эйри Ai(t), Bi(t). Здесь мы НЕ используем
#    точное решение; численная схема сравнивается с «эталонной» реализацией.
# -----------------------------------------------------------------------------
def _f_airy(t, Y):
    Y = np.atleast_1d(Y)
    return np.array([Y[1], t * Y[0]])


# -----------------------------------------------------------------------------
# 7. Уравнение Ван-дер-Поля ÿ = μ(1 − y²)·ẏ − y
#    Y = [y, ẏ]. μ = 1 даёт мягкий, но узнаваемый предельный цикл.
# -----------------------------------------------------------------------------
def make_vdp(mu: float = 1.0):
    def _f(t, Y):
        Y = np.atleast_1d(Y)
        return np.array([Y[1], mu * (1.0 - Y[0] ** 2) * Y[1] - Y[0]])
    return _f


# -----------------------------------------------------------------------------
# Каталог уравнений
# -----------------------------------------------------------------------------
EQUATIONS: dict[str, Equation] = {
    "linear": Equation(
        key="linear",
        name="ẏ = y",
        title="Линейное автономное ОДУ ẏ = y",
        f=_f_linear,
        y0=1.0,
        t0=0.0,
        tN=3.0,
        exact=_exact_linear,
        description=(
            "Каноническая задача из Fig.1 статьи. Точное решение y(t) = e^t. "
            "Лучшее место для наблюдения разницы порядков точности."
        ),
    ),
    "square": Equation(
        key="square",
        name="ẏ = y²",
        title="Нелинейное автономное ОДУ ẏ = y²",
        f=_f_square,
        y0=1.0,
        t0=0.0,
        tN=0.5,           # ограничиваем 0.5, чтобы не подойти к особенности t=1
        exact=_exact_square,
        description="Решение y(t)=1/(1−t) имеет конечное время взрыва при t=1.",
    ),
    "nlsin": Equation(
        key="nlsin",
        name="ẏ = 4y sin³(t) cos(t)",
        title="Нелинейное неавтономное ОДУ ẏ = 4y sin³(t) cos(t)",
        f=_f_nlsin,
        y0=1.0,
        t0=0.0,
        tN=5.0,
        exact=_exact_nlsin,
        description="Точное решение y(t)=exp(sin⁴ t) — гладкое и осциллирующее.",
    ),
    "cos": Equation(
        key="cos",
        name="ẏ = cos(t)",
        title="Линейное неавтономное ОДУ ẏ = cos(t)",
        f=_f_cos,
        y0=0.0,
        t0=0.0,
        tN=2.0 * np.pi,
        exact=_exact_cos,
        description="Простейший пример с явным y(t)=sin(t).",
    ),
    "shm": Equation(
        key="shm",
        name="ÿ = −y",
        title="Гармонический осциллятор ÿ = −y",
        f=_f_shm,
        y0=np.array([1.0, 0.0]),
        t0=0.0,
        tN=4.0 * np.pi,
        exact=_exact_shm,
        description="Сводится к системе Ẏ = [Y₂, −Y₁]; y(t)=cos t.",
    ),
    "airy": Equation(
        key="airy",
        name="ÿ = t·y",
        title="Уравнение Эйри ÿ = t·y",
        f=_f_airy,
        y0=np.array([1.0, 0.0]),
        t0=0.0,
        tN=5.0,
        exact=None,
        description="Аналитическое решение через функции Эйри; здесь — численно.",
    ),
    "vdp": Equation(
        key="vdp",
        name="Ван-дер-Поль",
        title="Уравнение Ван-дер-Поля, μ=1",
        f=make_vdp(mu=1.0),
        y0=np.array([2.0, 0.0]),
        t0=0.0,
        tN=10.0,
        exact=None,
        description="Известный пример предельного цикла; используется в Fig.2.",
    ),
}


def list_equations() -> None:
    """Печатает короткую справку по всем уравнениям."""
    print("Доступные уравнения:")
    for k, eq in EQUATIONS.items():
        print(f"  [{k:7s}]  {eq.title}")
        print(f"            t ∈ [{eq.t0}, {eq.tN}], y₀ = {eq.y0}")
        print(f"            {eq.description}")
        print()


if __name__ == "__main__":
    list_equations()
